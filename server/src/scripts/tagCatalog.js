/**
 * 按**本地时区**格式化日期为 YYYY-MM-DD
 *
 * 为什么不能用 toISOString().slice(0,10)：
 * toISOString() 会先转成 UTC。在 GMT+8 下，本地 2026-06-08 00:00
 * 转成 UTC 是 2026-06-07 16:00，slice 后得到 "2026-06-07"，
 * 整整差一天 —— 会让「精度表存的周一」与「样本表算出的周一」对不上，
 * 导致按周匹配大面积失败、精度回退到整体均值，趋势被压平。
 */
export function toDateStr(d) {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

/**
 * 取某个日期所在周的周一（本地时区），返回 YYYY-MM-DD
 */
export function weekStartOf(dateLike) {
  const d = new Date(dateLike)
  d.setHours(0, 0, 0, 0)
  d.setDate(d.getDate() - ((d.getDay() + 6) % 7))
  return toDateStr(d)
}

