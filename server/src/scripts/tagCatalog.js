// 目标簇总数（用户指定 500）。
// 每标签只有 2 条基础文案，簇靠「基础文案 × 前缀变体」派生，
// 具体生成逻辑见 expandSamples.js 的 clustersForTag / makeClusterText。
export const TARGET_CLUSTERS = 500
// 30 个标签凑 500 簇：前 20 个标签各 17 簇，后 10 个标签各 16 簇
export function clustersForTag(tagIdx) {
  const base = Math.floor(TARGET_CLUSTERS / TAGS.length) // 16
  const extra = TARGET_CLUSTERS - base * TAGS.length      // 20
  return base + (tagIdx < extra ? 1 : 0)
}
